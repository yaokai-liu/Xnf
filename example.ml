Definition (limit of sequence) {
    limit of sequence{a(n)} is a real number{a} that $\forall \epsilon \in R > 0$,
    $\exists N \in \mathbb{N} > 0$ that $\forall n > N$ there is $|a(n) - a| < \epsilon$.
} denote {
    [limit of sequence] (sequence{a(n)}) as $ \lim_{#{n}\to\infty}#{a(n)} $;
}

Definition (limit of sequence) {
    limit of function{f(x)} at $x_0 \in R$ is one real number{a} that $\forall \epsilon \in R > 0$,
    $\exists \delta \in R : \delta > 0$ that $\forall x : |x - x_0| < \delta$ there is $|f(x) - a| < \epsilon$.
} denote {
    [limit of function] (function{f(x)}, target{x_0}) as $ \lim_{#{x}\to#{x_0}}#{f(x)} $;
}
